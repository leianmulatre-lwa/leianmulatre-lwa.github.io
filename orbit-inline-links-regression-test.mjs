import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const read=file=>readFileSync(new URL('./'+file,import.meta.url),'utf8');
const pages=read('module-pages.js');
const css=read('orbit-cards-unified-20261016.css');
const route=read('politc-route-guard.js');
const html=read('index.html');
const fb=read('facebook-orbit.js');
assert.doesNotThrow(()=>new Script(pages),'Orbit module must parse');
assert.doesNotThrow(()=>new Script(route),'route guard must parse');
assert.match(pages,/function orbitLinkEditor\(k,name,url\)/,'All links share a single dialog editor');
assert.ok(pages.includes('data-orbit-edit-link=')&&pages.includes('data-orbit-link-dialog='),'Cards have an inline Link button and a separate accessible editor');
assert.ok(pages.includes('dialog?.showModal')&&pages.includes('data-orbit-close-link'),'Link editor opens and closes without enlarging cards');
assert.ok(pages.includes('data-orbit-save=')&&pages.includes('await manager.save(k,url)'),'Account-link save behavior remains');
assert.ok(!pages.includes('<div class="orbit-facebook-profile"><label')&&!pages.includes('<div class="orbit-link-utility"><label'),'No app reserves an extra link row');
assert.ok(pages.includes("grid.dataset.orbitSized='140'"),'Renderer applies 140px geometry');
assert.ok(css.includes('height:140px!important')&&css.includes('grid-template-areas:"head" "preview" "actions"'),'CSS matches renderer with 3 visible rows');
assert.ok(css.includes('.orbit-link-dialog[open]')&&css.includes('.orbit-link-dialog::backdrop'),'Editor uses the modal top layer');
assert.ok(pages.includes('data-orbit-connect=')&&pages.includes('data-facebook-legacy-connect'),'Provider auth buttons are intact');
assert.ok(fb.includes("one('.orbit-link-dialog-actions', card)"),'Meta media option does not add a card row');
const current='/module-pages.js?v=20261024-unified-links-2';
assert.ok(route.includes(current)&&pages.includes(current)&&html.includes(current),'All dynamically loaded module URLs use the same new build');
assert.ok(html.includes('politc-route-guard.js?v=20261023-x-scope-diagnostic-4'),'Route guard gets a fresh version');
assert.ok(html.includes('orbit-cards-unified-20261016.css?v=20261017-orbit-inline-links-1'),'Orbit layout stylesheet is cache-busted');
console.log('PASS: Orbit link button inline, modal edit/save, 140px cards, unified current module load paths');
