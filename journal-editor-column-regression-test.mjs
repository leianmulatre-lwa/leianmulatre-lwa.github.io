import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const {JSDOM}=createRequire(import.meta.url)('jsdom');
const read=p=>readFileSync(new URL('./'+p,import.meta.url),'utf8');
const pages=read('module-pages.js');
const collection=read('writing-collections.js');
const css=read('writing-collections.css');
const html=read('index.html');

assert(html.includes('writing-collections.css?v=20261029-journal-column-2'),'Latest Journal styling is included');
assert(html.includes('module-pages.js?v=20261029-arcade-links-keys-7'),'Latest Journal markup is included');
assert(pages.includes("if(visibility)form.append(visibility);"),'Visibility controls move to the editor rather than waiting beneath the page sidebar');
assert(css.includes('min-height:clamp(560px,72vh,780px)!important;'),'Lined Journal paper grows taller');
assert(css.includes('#moduleWritingForm > #journalShareControls.journal-owner-share'),'Visibility card width is tied to the writing column');

const dom=new JSDOM('<!doctype html><html><head></head><body><main id="studioApp"><div class="main"><article id="diary" class="card"></article></div></main></body></html>',{url:'https://biglwa.com/studio',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
w.eval(collection);
w.eval(pages);
assert.equal(typeof w.BigLWAOpenModule,'function','Real Studio module router initialized');
w.BigLWAOpenModule('diary');
const form=d.getElementById('moduleWritingForm');
const sidebar=d.querySelector('.writing-collection-sidebar');
const visibility=d.getElementById('journalShareControls');
const paper=d.getElementById('moduleWritingArea');
const privateStatus=d.getElementById('moduleWritingStatus');
assert(form&&sidebar&&visibility&&paper&&privateStatus,'Journal editor, page list and publishing controls mount');
assert.equal(visibility.parentElement,form,'Visibility panel is within right-side writing column');
assert.equal(visibility.previousElementSibling,privateStatus,'Visibility immediately follows private-draft status');
assert.equal(sidebar.parentElement,d.getElementById('diaryWritingSection'),'Page list remains beside the writing form');
assert.equal(form.parentElement,sidebar.parentElement,'Sidebar and editor preserve two-column structure');
assert.equal(visibility.querySelector('#journalPublish').type,'button','Publish is not an accidental form submit');
assert.equal(visibility.querySelector('#journalUnpublish').type,'button','Unpublish is not an accidental form submit');
paper.value='A private journal note';
form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
assert.equal(w.localStorage.getItem('biglwaDraft_diary'),'A private journal note','Save still preserves private draft');
const view=d.getElementById('journalViewButton');
view.click();
assert.equal(d.getElementById('diaryWritingSection').hidden,true,'Read mode hides editing sidebar and controls');
assert.equal(visibility.hidden,true,'Read mode does not expose publishing controls');
d.getElementById('journalReturnEdit').click();
assert.equal(d.getElementById('diaryWritingSection').hidden,false,'Editing resumes');
assert.equal(visibility.hidden,false,'Publishing options are restored');
assert.equal(visibility.parentElement,form,'Visibility stays anchored under private draft after returning');
w.close();
console.log('PASS: Journal page/visibility layout, enlarged writing area, private save, reader toggles and publishing controls');
