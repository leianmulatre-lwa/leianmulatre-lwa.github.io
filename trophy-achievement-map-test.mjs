import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const {JSDOM}=createRequire(import.meta.url)('jsdom');
const dom=new JSDOM('<div class="profile-copy"><div class="real-rank"><strong>007</strong></div></div><div id="map"></div>',{runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,host=w.document.getElementById('map');
w.eval(readFileSync(new URL('./trophy-achievement-map.js',import.meta.url),'utf8'));
const items=[{title:'First show',organization:'My studio',url:'https://example.com/proof'}];
w.BigLWATrophyMap.mount(host,items);
assert.equal(host.querySelectorAll('.trophy-node').length,7);
assert.equal(host.querySelectorAll('.trophy-node.earned').length,3,'Only reached ranks and saved trophy unlocked');
host.querySelector('[data-achievement="rank-5"]').click();
assert.match(host.querySelector('.trophy-map-detail').textContent,/Icon · Locked/);
host.querySelector('[data-achievement="trophy-0"]').click();
assert.equal(host.querySelector('.trophy-map-detail a').target,'_blank');
assert.equal(host.querySelector('.trophy-map-detail a').href,'https://example.com/proof');
const zoom=host.querySelector('output').value;
host.querySelector('[data-map-zoom="in"]').click();
assert.notEqual(host.querySelector('output').value,zoom);
const world=host.querySelector('.trophy-map-world'),before=world.style.transform;
host.querySelector('.trophy-map-viewport').dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true,cancelable:true}));
assert.notEqual(world.style.transform,before,'Arrow keys pan the map');
w.BigLWATrophyMap.mount(host,items);
assert.equal(host.querySelectorAll('[data-achievement="trophy-0"]').length,1,'Repaint preserves one saved trophy');
assert.equal(items.length,1,'Exploring does not mutate saved data');
dom.window.close();
console.log('PASS trophy map: real rank, locked states, saved trophies, links, zoom, keyboard pan and remount');
