import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const code=read('lwazi-search-ui.js'),css=read('lwazi-search-ui.css'),entry=read('index.html'),search=read('user-search-results.js');
const win={},sandbox={window:win,console,location:{origin:'https://biglwa.com'}};
vm.runInNewContext(code,sandbox,{filename:'lwazi-search-ui.js'});
const ui=win.__biglwaLwaziSearchUi;
assert.equal(typeof ui.decorateCard,'function');
assert.equal(typeof ui.bind,'function');
assert.equal(typeof ui.refresh,'function');
const card=ui.decorateCard('<article class="bl-search-card bl-media-card"><h3>Who made this</h3></article>',0,'Books');
assert.match(card,/class="bl-search-card bl-media-card veve-tile veve-book bl-search-veve-card"/);
for(const type of ['block','hide','open'])assert.match(card,new RegExp('data-bl-result-action="'+type+'"'));
assert.equal((card.match(/class="bl-card-dot /g)||[]).length,3);
assert.match(code,/Only this result/);
assert.match(code,/A subject or phrase I choose/);
assert.match(code,/Results from this source/);
assert.match(code,/Words or topic to avoid/);
assert.match(code,/Nothing was blocked/);
assert.match(code,/Manage blocked results/);
assert.match(code,/storage\(\)\.setItem\(storageKey\(\)/);
assert.match(code,/owner\(\)==='guest'\?sessionStorage:localStorage/,'Unsigned visitors cannot persist blocks across accounts');
assert.match(code,/window\.__biglwaIdentity\?\.uid/);
assert.doesNotMatch(code,/fetch\(|XMLHttpRequest|sendBeacon/,'Block choices and reasons never upload to an AI service');
assert.match(css,/\.veve-tile/);
assert.match(css,/--widget-bg/);
assert.match(css,/\.bl-card-block/);
assert.match(css,/\.bl-card-hide/);
assert.match(css,/\.bl-card-open/);
assert.match(css,/grid-template-columns:22px max-content/,'Category icons and labels share an aligned grid');
assert.match(css,/padding-left:var\(--bl-search-left,12px\)/,'Search gutter follows the live Skeleton Key');
assert.match(entry,/lwazi-search-ui\.css\?v=/);
assert.match(entry,/lwazi-search-ui\.js\?v=/);
assert.match(search,/bl-search-book/);
assert.match(search,/bl-search-song/);
console.log('PASS · Lwazi Veve card reuse, meaningful block controls, layout, icon alignment and source wiring');
