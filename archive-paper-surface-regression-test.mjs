import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('./'+p,import.meta.url),'utf8');
const page=read('module-pages.js');
const index=read('index.html');
const css=read('archive-flat-gallery-20261026.css');
const root='html body #studioApp #moduleWorkspace[data-module-key="archive"] ';
const rule=sel=>{
  const i=css.indexOf(sel);
  assert.ok(i>=0,'Archive CSS missing selector: '+sel);
  return css.slice(css.indexOf('{',i)+1,css.indexOf('}',i));
};
assert.ok(/archive-flat-gallery-20261026\.css\?v=[\w.-]+/.test(index),'New dedicated CSS file loaded by the actual Studio shell');
assert.ok(/module-pages\.js\?v=[\w.-]+/.test(index),'Current flat-gallery renderer is used, not stale accordion module');
assert.match(rule(root+'.archive-wall-shell'),/background:#faf6ef!important/,'One opaque paper shelf');
assert.match(rule(root+'.archive-toolbar'),/grid-template-columns:max-content minmax\(0,1fr\)/,'Buttons stay left while filters fill the right');
assert.match(rule(root+'.archive-filter-bar'),/justify-content:flex-end!important/,'App choices are top-right');
assert.match(rule(root+'.archive-page-list'),/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/,'Gallery is compact, multi-column, NOT full-width raw images');
assert.match(rule(root+'.archive-live'),/border-radius:999px!important/,'Live controls are pill switches on images');
assert.match(rule(root+'.archive-live input'),/opacity:0!important/,'Native raw checkbox hidden while remaining keyboard accessible');
assert.match(rule(root+'.archive-card-overlay'),/position:absolute!important/,'Card metadata and Live sit over the thumbnail, not below it');
assert.match(rule(root+'.archive-carousel-dots'),/position:absolute!important/,'Carousel dots stay within the image frame');
assert.doesNotMatch(page,/class="archive-app-compartment"/,'No redundant accordion markup remains');
assert.doesNotMatch(page,/class="archive-source-group"/,'No nested full-width platform panels remain');
assert.match(page,/return visible\.map\(index=>cardList\[index\]\)\.join\(''\)/,'One gallery for all card sources, preserving duplicate control');
assert.match(page,/f\.sources=k==='all'\?\[\]:\[k\]/,'Single-select source filters with All option');
assert.match(page,/aria-pressed/,'Exclusive filter selection is announced accessibly');
assert.match(page,/data-archive-live-input/,'Original account-backed Live state persists');
assert.match(page,/data-archive-source-filter/,'Source filters still exist');
assert.match(page,/archive-carousel-actions/,'Carousel controls still exist');
console.log('PASS Archive: dedicated stylesheet, single top-row toolbar, exclusive filters, flat dense cards, overlay switch and carousel.');
