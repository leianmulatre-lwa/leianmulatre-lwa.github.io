import assert from 'node:assert/strict';
import {readFileSync,existsSync,readdirSync} from 'node:fs';
import {Script} from 'node:vm';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const loading=read('studio-loading-dots-20261021.js');
const orbit=read('module-pages.js');
const orbitCss=read('orbit-cards-unified-20261016.css');
const tiktok=read('tiktok-orbit.js');
const readme=read('README.md');
assert.doesNotThrow(()=>new Script(loading),'Studio loading logic parses');
