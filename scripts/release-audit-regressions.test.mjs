assert.doesNotThrow(()=>new Script(tiktok),'TikTok connection logic parses');
assert.match(loading,/let moduleReadyCandidateAt=0,moduleRevealedFor='',moduleStableTimer=0/,'Loading curtain uses explicit settled state');
assert.match(loading,/moduleRevealedFor!==key/,'Curtain must be one-way after stable readiness');
assert.match(loading,/moduleReadyCandidateAt>=450/,'Readiness must remain stable before revealing');
assert.match(loading,/resetModuleReadiness\(\)/,'Navigation resets the latch');
assert.match(loading,/setTimeout\(\(\)=>\{moduleStableTimer=0;schedule\(\)\},480\)/);
assert.match(orbit,/overflow-x':'auto'/,'Orbit action rail scrolls rather than clips');
assert.match(orbit,/actions\.tabIndex=0/,'Orbit action rail is keyboard accessible');
assert.match(orbit,/flex':'0 0 auto'/,'Buttons cannot shrink to zero width');
assert.match(orbitCss,/overflow-x:auto!important/,'CSS layout agrees with JS');
assert.match(orbitCss,/flex:0 0 auto!important/,'CSS keeps Orbit actions reachable');
assert.match(orbit,/data-orbit-tiktok-sync/,'TikTok has an explicit account-scoped Sync now action');
assert.match(orbit,/await client\.restore\(\)/,'TikTok Sync now refreshes the account instead of restarting OAuth');
assert.match(tiktok,/lastCollectiveSync\}\}/,'TikTok exposes the last import result as status-only metadata');
assert.doesNotMatch(tiktok,/data-tt-actions/,'TikTok must not inject duplicate actions into Orbit');
assert.doesNotMatch(tiktok,/data-tiktok-video-sync-status/,'TikTok status cannot steal button width');
assert.match(tiktok,/data-orbit-row="tiktok"/,'TikTok displays diagnostics without duplicating controls');
assert.match(readme,/^# BIG LWA/m,'Repository title identifies BIG LWA');
assert.ok(!existsSync(new URL('../pyproject.toml',import.meta.url)),'No third-party pyproject in the website root');
assert.ok(!existsSync(new URL('../tweepy',import.meta.url)),'No top-level Tweepy source tree');
assert.ok(existsSync(new URL('../third_party/tweepy/tweepy/__init__.py',import.meta.url)),'Vendored Tweepy preserved');
assert.ok(existsSync(new URL('../third_party/tweepy/tests/test_client.py',import.meta.url)),'Vendored Tweepy tests preserved');
assert.ok(existsSync(new URL('../third_party/tweepy/LICENSE',import.meta.url)),'Upstream license preserved');
const vendorCassettes=readdirSync(new URL('../third_party/tweepy/cassettes/',import.meta.url));
const rootFixtures=readdirSync(new URL('../',import.meta.url)).filter(x=>/^test[a-z0-9_-]+\.(json|ya?ml)$/i.test(x));
assert.equal(rootFixtures.length,0,'Recorded Tweepy HTTP fixtures cannot occupy the BIG LWA website root');
assert.equal(vendorCassettes.length,140,'Every upstream Tweepy HTTP cassette must be preserved after migration');

assert.match(read('lwazi/policy.mjs'),/Privacy is the bare minimum|Privacy is the bare minimum, never a perk|Privacy should be the bare minimum/i,'Lwazi retains privacy ethic');
console.log('PASS release audit: loader latching, Orbit actions, TikTok single-owner UI, vendor source and Lwazi policy');
