/* Regression: full-page retro browser chrome never replaces the live apps. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const {JSDOM}=createRequire(import.meta.url)('jsdom');
const read=p=>readFileSync(new URL('./'+p,import.meta.url),'utf8');
const js=read('retro-browser-pages-20261029.js');
const css=read('retro-browser-pages-20261029.css');
const index=read('index.html');
assert(index.includes('retro-browser-pages-20261029.css?v=20261029-lwazi-unified-header-3'),'Page CSS ships');
assert(index.includes('retro-browser-pages-20261029.js?v=20261029-colored-buttons-2'),'Page chrome runtime ships');
assert(css.includes('[data-module-key="games"]'),'Games only page scope');
assert(css.includes('[data-module-key="tools"]'),'Lwazi only page scope');
assert(css.includes('module-arcade-controls{display:none!important}'),'Old joystick decoration retired');
assert(css.includes('is-quiz'),'Culture Quiz stays scrollable');
assert(!js.includes('.innerHTML='),'Page chrome must never replace application HTML');
const html=`<!doctype html><body><main id="studioApp"><section id="moduleWorkspace" data-module-key="games"><button id="moduleBack">Studio</button><section class="module-game-stage"><div id="biglwaArcadePlayer">Avatar</div><div class="module-arcade-folder-depth">Brand</div><div id="arcadeScreen" class="module-game-viewport"><button id="gameTile">Play</button><iframe id="gameIframe"></iframe></div></section></section></main></body>`;
const dom=new JSDOM(html,{url:'https://biglwa.com/studio',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
let backCount=0,gameCount=0,editorCount=0;
d.getElementById('moduleBack').addEventListener('click',()=>backCount++);
const originalScreen=d.getElementById('arcadeScreen');
const originalIframe=d.getElementById('gameIframe');
d.getElementById('gameTile').addEventListener('click',()=>gameCount++);
w.eval(js);
d.dispatchEvent(new w.Event('DOMContentLoaded'));
const flush=()=>new Promise(resolve=>setTimeout(resolve,75));
await flush();
const stage=d.querySelector('.module-game-stage');
assert.equal(stage.dataset.biglwaRetroBrowser,'games');
assert.equal(stage.querySelectorAll(':scope > .retro-window-chrome').length,1,'Exactly one Games toolbar');
assert.equal(stage.querySelectorAll(':scope > .retro-window-status').length,1,'Exactly one Games footer');
assert.strictEqual(d.getElementById('arcadeScreen'),originalScreen,'The playable screen remains same node');
assert.strictEqual(d.getElementById('gameIframe'),originalIframe,'Active game iframe not remounted');
d.getElementById('gameTile').click();
assert.equal(gameCount,1,'Game clicks remain attached');
stage.querySelector('.retro-window-close').click();
assert.equal(backCount,1,'X returns to Studio through the existing router');
d.getElementById('arcadeScreen').append(d.createElement('span'));
await flush();
assert.equal(stage.querySelectorAll(':scope > .retro-window-chrome').length,1,'Rerenders do not duplicate browser chrome');
const workspace=d.getElementById('moduleWorkspace');
workspace.dataset.moduleKey='tools';
const suite=d.createElement('section');
suite.id='craftSuite';
suite.className='craft-suite craft-workshop';
suite.innerHTML='<div class="craft-head">Launchers</div><button id="editorButton">Launch</button><section class="craft-panel"><iframe id="editorFrame"></iframe></section>';
workspace.append(suite);
d.getElementById('editorButton').addEventListener('click',()=>editorCount++);
const editorFrame=d.getElementById('editorFrame');
await flush();
assert.equal(suite.dataset.biglwaRetroBrowser,'lwazi');
assert.equal(suite.querySelectorAll(':scope > .retro-window-chrome').length,1,'Lwazi browser header present');
assert.strictEqual(d.getElementById('editorFrame'),editorFrame,'Editor iframe not re-created');
d.getElementById('editorButton').click();
assert.equal(editorCount,1,'Editor launch remains functional');
suite.innerHTML='<section class="craft-directory"><button id="newEditor">Another editor</button></section>';
await flush();
assert.equal(suite.querySelectorAll(':scope > .retro-window-chrome').length,1,'Live Lwazi remount restores one frame');
assert(suite.querySelector('#newEditor'),'New editor remains present');
suite.querySelector('.retro-window-close').click();
assert.equal(backCount,2,'Lwazi X returns to Studio');
const computedCss=css.toLowerCase();
assert(computedCss.includes('prefers-reduced-motion'),'Respects reduced motion');
w.close();
console.log('PASS: Games and Lwazi real browser pages, original iframe/tiles, remount and Studio back');
