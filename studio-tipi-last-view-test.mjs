function setup(uid,remote,search=''){
 const saved=new Map([['biglwaLastStudioView','orbit']]),calls=[],tasks=[],cloud=[];
 const store={getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)};
 const win={__biglwaIdentity:{uid},BigLWAUserDirectory:{saveCustomizations:x=>cloud.push(x)},openBIGLWAModule:key=>calls.push(key)};
 const context={window:win,location:{pathname:'/studio',search},localStorage:store,console,URLSearchParams,setTimeout:f=>tasks.push(f),
   document:{readyState:'loading',addEventListener(){},documentElement:{classList:{contains:()=>false}},querySelector:()=>null}};
 const where=session.lastIndexOf('})();');
 assert(where>0,'Restoration module footer found');
 const source=session.slice(0,where)+'window.__studioRestoreTest={setLastView,restoreLastView,lastViewFromLocal};\n'+session.slice(where);
 vm.runInNewContext(source,context);
 return {api:win.__studioRestoreTest,win,context,saved,calls,tasks,cloud,remote};
}
const a=setup('member-one',{customization:{session:{lastView:'orbit'}}});
a.api.restoreLastView(a.remote);
assert.equal(a.tasks.length,0,'An old generic Orbit setting does not force an Orbit landing');
a.api.setLastView('projects');
assert.equal(a.saved.get('biglwaLastStudioView:v2:member-one'),'projects','Module view is scoped to signed-in UID');
a.api.restoreLastView(a.remote);
assert.equal(a.tasks.length,1);
a.tasks.shift()();
assert.deepEqual(a.calls,['projects'],'The last active widget is restored');
a.api.setLastView('studio');
assert.equal(a.saved.get('biglwaLastStudioView:v2:member-one'),'studio','Returning home persists Studio rather than clearing only local history');
assert.equal(a.cloud.at(-1).session.lastView,'studio','Home also replaces stale remote view');
const b=setup('member-two',{customization:{session:{lastView:'orbit'}}});
assert.equal(b.api.lastViewFromLocal(),'','Second user cannot inherit member-one local view');
