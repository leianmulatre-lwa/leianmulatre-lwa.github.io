/* Spatial regression: Highlights drag editing and Pinterest-style Archive walls. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const read=p=>readFileSync(new URL('./'+p,import.meta.url),'utf8');
const js=read('profile-highlight-editor.js');
const css=read('archive-highlights-masonry-adjust-20261029.css');
const index=read('index.html');
assert.doesNotThrow(()=>new Script(js),'Highlights editor remains valid JavaScript');
assert(index.includes('archive-highlights-masonry-adjust-20261029.css?v=20261029-space-flow-1'),'Final Archive masonry CSS is loaded');
assert(index.includes('profile-highlight-editor.js?v=20261029-drag-masonry-4'),'Fresh Highlight editor JS is loaded');
assert(index.includes('profile-highlight-editor.css?v=20261029-drag-masonry-4'),'Fresh Highlight CSS is loaded');
assert(js.includes("container.dataset.highlightLayout=platform==='snapchat'||(groups.length+custom.length<=1)?'single':'masonry'"),'Snapchat is always full-width; single groups use full width');
assert(css.includes('.highlight-edit-list[data-highlight-layout="single"]'),'Single group spans entire editor');
assert(css.includes('columns:2!important'),'Imported groups use two flowing columns instead of equal-height grid rows');
assert(css.includes('break-inside:avoid!important'),'Cards stay intact across columns');
assert(css.includes('grid-template-columns:repeat(auto-fit,minmax('),'Gallery fits 5+ items when space allows');
assert(css.includes('.archive-page-list>.instagram-archive-card'),'Archive cards follow multi-column flow across apps');
for(const count of [8,7,5,3,2])assert(css.includes('columns:'+count+'!important'),'Responsive Archive width supports '+count+' columns');
assert(js.includes("circle.addEventListener('pointerdown'"),'Cover can be dragged');
assert(js.includes("circle.addEventListener('pointermove'"),'Cover follows pointer');
assert(js.includes("circle.addEventListener('keydown'"),'Keyboard alternative for position');
assert(js.includes("adjustButton.setAttribute('aria-pressed'"),'Adjust button communicates state');
assert(js.includes('if(!adjusting||event.button!==0)return'),'Dragging is opt-in rather than interfering with scrolling');
assert(!js.includes("range.type='range';range.min=0;range.max=100"),'Old cover x/y sliders retired');
assert(js.includes('x:raw.x==null||!Number.isFinite(Number(raw.x))?50'),'Left edge cropping survives account save');
assert(js.includes('y:raw.y==null||!Number.isFinite(Number(raw.y))?50'),'Top edge cropping survives account save');
assert(js.includes('saveCustomizations?.({session:{highlightEdits:payload}})'),'Saved edits still sync to account');
assert(js.includes('checkbox.checked=selection.includes(i)'),'Existing Live selections still honored');
console.log('PASS Highlights: draggable adjustment, snap single layout, dense photo gallery, multi-source Archive masonry and account sync');
