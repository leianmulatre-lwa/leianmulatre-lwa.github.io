import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const {JSDOM}=createRequire(import.meta.url)('jsdom');
const source=readFileSync(new URL('./studio-media-adjust-20261027.js',import.meta.url),'utf8');
const wallpaper=readFileSync(new URL('./studio-appearance.js',import.meta.url),'utf8');
const photo=readFileSync(new URL('./profile-highlight-editor.js',import.meta.url),'utf8');
const cloud=readFileSync(new URL('./account-photo.js',import.meta.url),'utf8');
const directory=readFileSync(new URL('./firebase-directory.js',import.meta.url),'utf8');
const index=readFileSync(new URL('./index.html',import.meta.url),'utf8');
const dom=new JSDOM('<!doctype html><html><head></head><body></body></html>',{
 url:'https://biglwa.com/studio',runScripts:'outside-only',pretendToBeVisual:true
});
const w=dom.window,q=s=>w.document.querySelector(s);
w.HTMLDialogElement.prototype.showModal=function(){this.open=true};
w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'))};
w.eval(source);
assert(w.BIGLWAMediaAdjust,'Reusable drag-to-adjust controls installed');
assert.equal(w.BIGLWAMediaAdjust.parsePosition('30% 70%').y,70);
assert(wallpaper.includes("row.insertBefore(adjust,remove)"),'Adjust goes between Choose and Remove');
assert(wallpaper.includes('wallpaper-position-native'),'Fit and Position move out of the primary panel');
assert(wallpaper.includes('currentWallpaperSettings()'),'Wallpaper coordinates remain in saved settings');
assert(photo.includes("id='adjustProfilePicture'")||photo.includes("adjust.id='adjustProfilePicture'"),'Profile Picture offers Adjust');
assert(cloud.includes("profilePhotoPosition:values"),'Photo coordinates are account and public synced');
assert(directory.includes("position:safeText(wallpaper.position,32)"),'Wallpaper position mirrors to public profiles');
assert(index.includes('/studio-media-adjust-20261027.js?v='),'Site loads the adjust popup');
const editor=w.BIGLWAMediaAdjust;
let saved=null;
assert.equal(editor.open({type:'wallpaper',url:'https://example.com/wallpaper.jpg',position:'50% 50%',fit:'cover',onSave:data=>{saved=data}}),true);
const dialog=q('#biglwaMediaAdjust'),stage=q('#mediaAdjustStage'),img=stage.querySelector('img');
assert(dialog.open&&img&&q('#mediaAdjustFit').value==='cover');
Object.defineProperties(stage,{clientWidth:{configurable:true,get:()=>400},clientHeight:{configurable:true,get:()=>200}});
Object.defineProperties(img,{naturalWidth:{configurable:true,get:()=>800},naturalHeight:{configurable:true,get:()=>800}});
stage.dispatchEvent(new w.MouseEvent('pointerdown',{bubbles:true,button:0,clientX:140,clientY:90}));
w.document.dispatchEvent(new w.MouseEvent('pointermove',{bubbles:true,clientX:140,clientY:130}));
w.document.dispatchEvent(new w.MouseEvent('pointerup',{bubbles:true}));
assert.equal(img.style.objectPosition,'50.0% 30.0%','Dragging the image shifts its vertical crop using actual overflow');
q('#mediaAdjustSave').click();
await new Promise(resolve=>setTimeout(resolve,2));
assert.equal(saved.position,'50.0% 30.0%');
assert.equal(dialog.open,false);
assert.equal(editor.open({type:'photo',url:'https://example.com/photo.jpg',position:'30% 60%',onSave:()=>{throw Error('Save should not run on Cancel')}}),true);
assert(stage.classList.contains('is-photo'),'Photo preview uses a round crop');
q('#mediaAdjustCenter').click();assert.equal(stage.querySelector('img').style.objectPosition,'50.0% 50.0%');
q('#mediaAdjustCancel').click();assert(!dialog.open,'Cancel exits without committing');
dom.window.close();
console.log('PASS wallpaper and profile photo drag-to-align; correct layout, persistent account position, cancel/reset, public mirror');
