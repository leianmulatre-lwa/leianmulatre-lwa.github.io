import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const {JSDOM}=createRequire(import.meta.url)('jsdom');
const read=p=>readFileSync(new URL('./'+p,import.meta.url),'utf8');
const code=read('module-pages.js'),map=read('trophy-achievement-map.js'),styles=read('studio-trophy-versions-symbol-bounds-20261029.css'),index=read('index.html');
assert(index.includes('module-pages.js?v=20261029-arcade-links-keys-7'));
assert(index.includes('trophy-achievement-map.js?v=20261029-rank-only-1'));
assert(index.includes('studio-trophy-versions-symbol-bounds-20261029.css'));
assert(!code.includes('<b>No trophies yet</b>'),'Do not show a redundant empty-state below achievement artwork');
assert(code.includes('preview.querySelectorAll(\'.trophy-preview-count,.trophy-preview-item,.trophy-preview-empty\')'),'Keep saved data but preserve the artwork');
assert(code.includes("['rank','Real Rank'")&&code.includes("['case','Trophy Case'"),'Two versions exist');
assert(code.includes("{mode:'rank'}"),'Real Rank is a separate rank-only map');
assert(styles.includes('.trophy-version-pane[hidden]'),'Hidden version remains hidden despite grid styles');
assert(!styles.includes('.biglwa-topbar-current'),'Trophy page cannot override shared masthead geometry');
const dom=new JSDOM('<!doctype html><html><body><main id="studioApp"><div class="profile-copy"><div class="real-rank"><strong>007</strong></div></div><div class="main"><article id="trophies" class="card"><div id="trophyPreview"><img class="biglwa-default-trophy-image" src="/assets/studio-defaults/trophy-achievement-made.webp"></div></article></div></main></body></html>',{url:'https://biglwa.com/studio',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
w.scrollTo=()=>{};
w.HTMLElement.prototype.scrollIntoView=()=>{};
w.eval(map);
w.eval(code);
assert.equal(typeof w.BigLWAOpenModule,'function','Page router is initialized');
w.BigLWAOpenModule('trophies');
const rank=d.getElementById('trophyRankVersion'),casePanel=d.getElementById('trophyCaseVersion');
const tabs=[...d.querySelectorAll('.trophy-heading-versions button')];
assert(rank&&casePanel,'Real Rank and Trophy Case have independent content');
assert.deepEqual(tabs.map(el=>el.textContent),['Real Rank','Trophy Case']);
assert.equal(rank.hidden,false,'Real Rank defaults to its own page');
assert.equal(casePanel.hidden,true,'Trophy Case begins hidden');
assert.equal(d.querySelectorAll('#trophyAchievementMap [data-achievement^="rank-"]').length,6,'All six genuine rank nodes');
assert.equal(d.querySelectorAll('#trophyAchievementMap [data-achievement^="trophy-"]').length,0,'Real Rank map contains no user-submitted trophies');
tabs[1].click();
assert.equal(rank.hidden,true);
assert.equal(casePanel.hidden,false);
assert.equal(tabs[1].getAttribute('aria-pressed'),'true');
assert(d.getElementById('trophyForm')&&d.getElementById('trophyList'),'Trophy Case retains its editor and collection');
const preview=d.getElementById('trophyPreview');
assert(preview.querySelector('.biglwa-default-trophy-image'),'Achievement art persists');
assert(!preview.textContent.includes('No trophies yet'),'No duplicate empty-state beneath thumbnail');
const form=d.getElementById('trophyForm');
form.elements.namedItem('title').value='My first award';
form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
assert(d.getElementById('trophyList').textContent.includes('My first award'),'Saved trophy appears in case');
assert.equal(d.querySelectorAll('#trophyPreview .trophy-preview-item').length,1,'Studio preview shows saved entry');
tabs[0].click();
assert.equal(rank.hidden,false);
assert.equal(casePanel.hidden,true);
assert.equal(d.querySelectorAll('#trophyAchievementMap [data-achievement^="trophy-"]').length,0,'Saved case entries cannot appear as rank achievements');
assert.equal(preview.querySelectorAll('.biglwa-default-trophy-image').length,1,'Artwork not duplicated by redraw');
w.close();
console.log('PASS: Trophies page versions, rank-only map, save preview, bounded optical marks and preserved thumbnail');
