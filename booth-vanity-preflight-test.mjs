import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const read=name=>readFileSync(new URL('./'+name,import.meta.url),'utf8');
const pages=read('module-pages.js');
const heads=read('module-version-header-20261026.js');
const canvas=read('project-canvas.js');
const thumb=read('studio-uploaded-thumbnails-20261110.css');
assert.doesNotThrow(()=>new Script(pages),'Module JavaScript still parses');
assert.doesNotThrow(()=>new Script(heads),'Version header still parses');
assert.doesNotThrow(()=>new Script(canvas),'Project canvas still parses');
assert.match(heads,/notes:\{title:'sqwibbl\/r'/,'Sqwibbl/r keeps the original notes module route');
assert.match(heads,/projects:\{title:'visualiz\/r'/,'Visualiz/r keeps the original projects route');
assert.match(pages,/notes:'sqwibbl\/r',projects:'visualiz\/r'/,'Module heading labels updated together');
assert.match(canvas,/<h1>visualiz\/r<\/h1>/,'Visual workspace title remains in sync');
assert.match(pages,/font-family:"CS Bergamot Stitched","Bergamot Stitched"/,'Visualiz/r uses Sqwip screenplay heading font');
assert.match(pages,/<span aria-hidden="true">▤<\/span> Sqwib/,'Sqwib tab keeps its original archive mark');
assert.match(pages,/<span aria-hidden="true">♢<\/span> Sqwip/,'Sqwip tab keeps its original diamond mark');

const start=pages.indexOf('  function renderCamera()'),end=pages.indexOf('  /* Video Booth:',start);
assert(start>=0&&end>start,'Booth editor found');
const photo=pages.slice(start,end);
assert.match(photo,/id="boothVanity"/,'Booth has a vanity around its camera stage');
assert.match(photo,/id="boothProfilePhoto"/,'Booth uses member portrait rather than thumbnail');
assert.doesNotMatch(photo,/src="\/assets\/booth-light-20261029\.webp"/,'Studio thumbnail is not inserted into the Booth stage');
assert.match(photo,/id="boothLightLevel" type="range"/,'Vanity screen-light intensity can be adjusted');
assert.match(photo,/aria-pressed="true">Lights on/,'Lights can be toggled');
assert.match(photo,/biglwaOwnProfileV1:'\+uid/,'Profile photo is UID-scoped');
assert.match(photo,/who\.avatarUrl\|\|saved\.profilePhoto\?\.url/,'Authenticated profile photo is preferred');
assert.match(photo,/if\(document\.documentElement\.classList\.contains\('biglwa-preview-mode'\)\)/,'Public-preview users cannot read another account photo');
assert.match(photo,/stopCamera\(\);flip\.disabled=true;latestPhotoBlob=f/,'Selecting a file releases any active camera');
assert.match(photo,/if\(!video\)stopVideoTest\(\)/,'Leaving the Video Booth stops local media');
assert.match(photo,/videoTestStatus\.textContent='Your local camera preview is on\. No matching or video call is active\.'/,'Test preview does not pretend a call is connected');
assert.match(photo,/getUserMedia\(\{audio:true,video:false\}\)/,'Microphone preflight requires an explicit click');

const video=pages.slice(end,pages.indexOf('  const TRENDING_ROOMS',end));
assert.match(video,/id="videoBoothOwnPhoto"/,'Video Booth profile card can show the member portrait');
assert.match(video,/id="videoBoothSelfPreview"/,'Video Booth has its own local-only media element');
assert.match(video,/id="videoBoothRequestConnect" type="button" disabled/,'Random calls remain gated by consent and safety work');
assert.doesNotMatch(video,/photobooth-before-use\.webp/,'No fake person photo is shown for a stranger');
assert.match(pages,/function stopCamera\(\)\{[\s\S]{0,260}stopVideoTest\(\)/,'Leaving the module stops local camera preview');
assert.doesNotMatch(thumb,/#studioApp \.photobooth-stage \.photobooth-intro/,'Thumbnail CSS cannot replace the Booth profile image');
assert.match(thumb,/#studioApp #camera \.photobooth-reference-preview > img/,'Original Studio thumbnail remains unchanged');
assert.match(pages,/\.booth-vanity \.photobooth-stage\.has-intro/,'Vanity styling wins the legacy stage background rule');
console.log('PASS Lwazi titles, original writing symbols, Booth vanity, owner photo isolation, local-only media preflight and gated matching');
