assert.ok(modules.includes('data-silent-update'),'Privacy behavior preserved');
assert.ok(css.includes('grid-template-areas:"title shadow" "meta meta"'),'Two-row full-width heading');
assert.ok(html.indexOf('source-shadow-key-20261025.js')<html.indexOf('module-pages.js?v=20261026-boothi-studio-text-1'),'Shared module loads before pages');
assert.ok(html.indexOf('source-shadow-key-20261025.js')<html.indexOf('studio-onboarding.js?v=20261028-skeleton-stats-1'),'Shared module loads before Skeleton');

assert.ok(feed.includes('fillPublicAuthorAuras'),'myfeed loads author-owned public Aura, not viewer Aura');
assert.ok(feed.includes('postShadow(post,managed,displaySource)'),'myfeed applies provenance to actual cards');
assert.ok(feed.includes("shadow:'3px 3px 0 #ffffff'"),'Explicit paid media has one white shadow');
assert.ok(feed.includes('data-shadow-kind="lwa"'),'BIG LWA posts have a rainbow treatment');
assert.ok(providerFeed.includes("return '3px 3px 0 '+(look.rim"),'Connected providers have a single source shadow');
assert.ok(links.includes("'website'"),'Owner-scoped own-website link is available');
assert.ok(modules.includes("['website','WWW','My website'"),'Own website is a visible Orbit planet');
assert.ok(!profile.includes("||'B'"),'Avatar has no invented B fallback');
assert.ok(!chrome.includes('|| "B"'),'Top right identity chrome never invents B');
assert.ok(chrome.includes('const avatarName=name;'),'Chrome only accepts a chosen display name');
assert.ok(!boundary.includes("own?.name||own?.username||'B'"),'Startup state cannot restore the phantom B');
