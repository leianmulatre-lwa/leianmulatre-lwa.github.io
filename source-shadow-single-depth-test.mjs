import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const load=p=>readFileSync(new URL('./'+p,import.meta.url),'utf8');
const key=load('source-shadow-key-20261025.js');
const css=load('source-shadow-key-20261025.css');
const modules=load('module-pages.js');
const skeleton=load('studio-onboarding.js');
