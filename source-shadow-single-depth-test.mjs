import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const load=p=>readFileSync(new URL('./'+p,import.meta.url),'utf8');
const key=load('source-shadow-key-20261025.js');
const css=load('source-shadow-key-20261025.css');
const modules=load('module-pages.js');
const skeleton=load('studio-onboarding.js');
const html=load('index.html');
assert.doesNotThrow(()=>new Script(key));
assert.doesNotThrow(()=>new Script(modules));
assert.doesNotThrow(()=>new Script(skeleton));
let shared;
new Function('window',key+'; return window.BigLWAShadowKey;')((shared={}));
shared=shared.BigLWAShadowKey;
assert.equal(typeof shared?.render,'function');
const orbit=shared.render('orbit');
const archive=shared.render('archive');
const skeletonMarkup=shared.render('skeleton');
assert.equal((orbit.match(/class="shadow-preview"/g)||[]).length,22,'Orbit has all 22 origins');
assert.ok(orbit.includes('--key-shadow:#f36b21'),'Instagram has one orange source shadow');
assert.ok(archive.includes('--key-shadow:#1658be'),'Archive retains Facebook source tint');
assert.ok(css.includes('background:#eee7db'),'Every preview uses a neutral bone-ivory face');
assert.ok(orbit.includes('data-key-source="website"'),'Own website has an Aura-colored key');
assert.ok(orbit.includes('data-key-source="lwa"'),'BIG LWA rainbow key is present');
assert.ok(orbit.includes('data-key-source="ad"'),'Ads have a white shadow key');
assert.ok(!orbit.includes('Other source'),'No invented brown other-source category');
assert.ok(skeletonMarkup.includes('data-key-source="drive"'),'Skeleton contains Google Drive');
assert.ok(css.includes('box-shadow:3px 3px 0 var(--key-shadow'),'One shadow per key');
assert.ok(!css.includes('box-shadow:2px 2px 0'),'No second layered shadow');
assert.ok(modules.includes('window.BigLWAShadowKey?.render'),'Headers share same actual source data');
assert.ok(skeleton.includes("window.BigLWAShadowKey?.render?.('skeleton')"),'Skeleton shares source key');
assert.ok(skeleton.includes('skeleton-body-models'),'Three-body explanation kept');
assert.ok(modules.includes('module-heading--with-shadow'),'Key aligns with H1');
assert.ok(modules.includes('class="module-heading-bottom"'),'SEO description spans header below');
assert.ok(!modules.includes('<details class="module-heading-actions module-update-preferences"'),'Privacy checkbox is no longer behind a dropdown');
assert.ok(modules.includes('data-silent-update'),'Privacy behavior preserved');
assert.ok(css.includes('grid-template-areas:"title shadow" "meta meta"'),'Two-row full-width heading');
assert.ok(html.indexOf('source-shadow-key-20261025.js')<html.indexOf('module-pages.js?v=20261025-source-face-1'),'Shared module loads before pages');
assert.ok(html.indexOf('source-shadow-key-20261025.js')<html.indexOf('studio-onboarding.js?v=20261025-skeleton-shadow-key-1'),'Shared module loads before Skeleton');
console.log('PASS one source shadow + widget face, shared Skeleton key, wide SEO heading, inline privacy');
